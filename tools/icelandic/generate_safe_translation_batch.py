def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("input_csv", type=Path)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()

    with args.input_csv.open("r", encoding="utf-8-sig", newline="") as f:
        rows = list(csv.DictReader(f))
        fieldnames = list(rows[0].keys()) if rows else []

    out: list[dict[str, str]] = []
    for row in rows:
        if row.get("kind") != "untranslated":
            continue
        text = (row.get("current_text") or "").strip()
        translated = EXACT.get(text)
        if translated is None:
            continue
        new_row = dict(row)
        new_row["icelandic"] = translated
        out.append(new_row)

    args.output.parent.mkdir(parents=True, exist_ok=True)
    with args.output.open("w", encoding="utf-8-sig", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(out)

    print(f"selected={len(out)} output={args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
